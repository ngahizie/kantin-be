-- ---------------------------------------------------------------------
-- Acuan: docs/skema-v2/ (erd-v2.mmd + dokumentasi-skema.md)
--
-- Migrasi ini BUKAN bangun-ulang: data lama dipertahankan, hanya bentuk
-- skemanya yang dirapikan. Karena itu aman dijalankan pada DB dev yang
-- sudah berisi data.
