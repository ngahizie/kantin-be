-- ---------------------------------------------------------------------
-- 3. dev_siswa_rfid dipecah: siswa (identitas) + kartu (fisik)
-- ---------------------------------------------------------------------
create table siswa (
    id          bigint generated by default as identity primary key,
    sekolah_id  bigint not null,
    nis         varchar(30) not null,
    nisn        varchar(30),
    nama        varchar(100) not null,
    kelas       varchar(30),
    foto_url    varchar(255),
    aktif       boolean not null default true,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint uq_siswa_sekolah_nis  unique (sekolah_id, nis),
    constraint uq_siswa_sekolah_id   unique (sekolah_id, id),
    constraint fk_siswa_sekolah      foreign key (sekolah_id) references sekolah (id)
);

create table kartu (
    uid         varchar(50) primary key,
    sekolah_id  bigint not null,
    siswa_id    bigint not null,
    nomor_kartu varchar(32) not null,
    aktif       boolean not null default true,
    created_at  timestamptz not null default now(),
    constraint uq_kartu_sekolah_nomor unique (sekolah_id, nomor_kartu),
    constraint fk_kartu_siswa   foreign key (sekolah_id, siswa_id)
        references siswa (sekolah_id, id) on delete cascade,
    constraint fk_kartu_sekolah foreign key (sekolah_id) references sekolah (id)
);

-- satu siswa hanya boleh punya satu kartu aktif
create unique index uq_kartu_siswa_aktif on kartu (sekolah_id, siswa_id) where aktif;

insert into siswa (id, sekolah_id, nis, nama, kelas, aktif)
select d.siswa_id,
       d.sekolah_id,
       d.siswa_id::text,
       coalesce(nullif(d.nama, ''), 'Siswa ' || d.siswa_id),
       d.kelas,
       d.aktif
from dev_siswa_rfid d;

-- Data lama tidak sepenuhnya konsisten: ada saldo/transaksi milik siswa yang
-- sudah tidak ada di dev_siswa_rfid (mis. siswa_id 9 dan 1004). Supaya riwayat
-- keuangannya tidak hilang, siswa tersebut dibuatkan baris penampung.
insert into siswa (id, sekolah_id, nis, nama)
select distinct x.subjek_id, x.sekolah_id, 'LAMA-' || x.subjek_id, 'Siswa ' || x.subjek_id || ' (arsip)'
from (
    select sekolah_id, subjek_id from saldo               where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from mutasi_saldo  where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from transaksi     where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from transaksi_tertunda where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from blokir_kartu  where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from blokir_item   where subjek_tipe = 'SISWA'
    union select sekolah_id, subjek_id from limit_harian  where subjek_tipe = 'SISWA'
) x
where not exists (
    select 1 from siswa s where s.sekolah_id = x.sekolah_id and s.id = x.subjek_id
);

insert into kartu (uid, sekolah_id, siswa_id, nomor_kartu, aktif)
select d.rfid_uid, d.sekolah_id, d.siswa_id, d.nomor_kartu, d.aktif
from dev_siswa_rfid d;

drop table dev_siswa_rfid;

-- ---------------------------------------------------------------------
-- 4. Tabel orang tua / wali
-- ---------------------------------------------------------------------
create table orang_tua (
    id             bigint generated by default as identity primary key,
    sekolah_id     bigint not null,
    siswa_id       bigint not null,
    nama           varchar(100) not null,
    telepon        varchar(30),
    hubungan       varchar(20) not null default 'WALI',
    punya_aplikasi boolean not null default false,
    aktif          boolean not null default true,
    created_at     timestamptz not null default now(),
    constraint ck_orang_tua_hubungan check (hubungan in ('AYAH','IBU','WALI')),
    constraint fk_orang_tua_siswa   foreign key (sekolah_id, siswa_id)
        references siswa (sekolah_id, id) on delete cascade,
    constraint fk_orang_tua_sekolah foreign key (sekolah_id) references sekolah (id)
);

comment on table orang_tua is 'Wali siswa. Satu siswa boleh punya lebih dari satu baris (ayah, ibu, wali).';

-- ---------------------------------------------------------------------
-- 5. subjek_tipe/subjek_id (polimorfik) -> siswa_id
-- ---------------------------------------------------------------------
-- 5a. saldo: PK (subjek_tipe, subjek_id) -> (sekolah_id, siswa_id)
alter table saldo drop constraint pk_saldo_cache;
alter table saldo drop constraint ck_saldo_cache_subjek_tipe;
alter table saldo add column siswa_id bigint;
update saldo set siswa_id = subjek_id where subjek_tipe = 'SISWA';
delete from saldo where subjek_tipe <> 'SISWA';
alter table saldo drop column subjek_tipe;
alter table saldo drop column subjek_id;
alter table saldo alter column siswa_id set not null;
alter table saldo add constraint pk_saldo primary key (sekolah_id, siswa_id);
alter table saldo add constraint fk_saldo_siswa foreign key (sekolah_id, siswa_id)
    references siswa (sekolah_id, id) on delete cascade;

-- 5b. mutasi_saldo (dulu saldo_ledger)
-- ledger bersifat append-only (trigger menolak UPDATE/DELETE); migrasi ini
-- perlu menulis ulang kolomnya, jadi trigger dimatikan sementara.
alter table mutasi_saldo disable trigger user;
drop index if exists idx_saldo_ledger_subjek;
alter table mutasi_saldo drop constraint ck_saldo_ledger_subjek_tipe;
alter table mutasi_saldo add column siswa_id bigint;
update mutasi_saldo set siswa_id = subjek_id where subjek_tipe = 'SISWA';
delete from mutasi_saldo where subjek_tipe <> 'SISWA';
alter table mutasi_saldo drop column subjek_tipe;
alter table mutasi_saldo drop column subjek_id;
alter table mutasi_saldo alter column siswa_id set not null;
alter table mutasi_saldo add constraint fk_mutasi_saldo_siswa foreign key (sekolah_id, siswa_id)
    references siswa (sekolah_id, id) on delete cascade;
create index idx_mutasi_saldo_siswa on mutasi_saldo (sekolah_id, siswa_id, waktu desc);
alter table mutasi_saldo enable trigger user;

-- 5c. transaksi
alter table transaksi drop constraint ck_transaksi_subjek_tipe;
alter table transaksi add column siswa_id bigint;
update transaksi set siswa_id = subjek_id where subjek_tipe = 'SISWA';
delete from transaksi where subjek_tipe <> 'SISWA';
alter table transaksi drop column subjek_tipe;
alter table transaksi drop column subjek_id;
alter table transaksi alter column siswa_id set not null;
alter table transaksi add constraint fk_transaksi_siswa foreign key (sekolah_id, siswa_id)
    references siswa (sekolah_id, id);
create index idx_transaksi_siswa on transaksi (sekolah_id, siswa_id, waktu desc);

-- 5d. transaksi_tertunda (dulu transaksi_menunggu_konfirmasi)
alter table transaksi_tertunda add column siswa_id bigint;
update transaksi_tertunda set siswa_id = subjek_id;
alter table transaksi_tertunda drop column subjek_tipe;
alter table transaksi_tertunda drop column subjek_id;
alter table transaksi_tertunda alter column siswa_id set not null;
alter table transaksi_tertunda add constraint fk_transaksi_tertunda_siswa
    foreign key (sekolah_id, siswa_id) references siswa (sekolah_id, id);

-- 5e. Transaksi lama memakai uid kartu yang sudah tidak terdaftar (kartu
-- siswa yang sudah dihapus). Kartunya dibuat ulang sebagai arsip (aktif=false)
-- supaya riwayat transaksi tetap punya rujukan.
insert into kartu (uid, sekolah_id, siswa_id, nomor_kartu, aktif)
select x.uid, x.sekolah_id, x.siswa_id, 'ARSIP-' || x.uid, false
from (
    select distinct on (kartu_uid) kartu_uid as uid, sekolah_id, siswa_id
    from transaksi where kartu_uid is not null
    order by kartu_uid, waktu desc
) x
where not exists (select 1 from kartu k where k.uid = x.uid);

insert into kartu (uid, sekolah_id, siswa_id, nomor_kartu, aktif)
select x.uid, x.sekolah_id, x.siswa_id, 'ARSIP-' || x.uid, false
from (
    select distinct on (rfid_uid) rfid_uid as uid, sekolah_id, siswa_id
    from transaksi_tertunda where rfid_uid is not null
    order by rfid_uid, dibuat_at desc
) x
where not exists (select 1 from kartu k where k.uid = x.uid);

-- ---------------------------------------------------------------------
-- 6. blokir_kartu + blokir_item + limit_harian -> pembatasan
-- ---------------------------------------------------------------------
create table pembatasan (
    id          bigint generated by default as identity primary key,
    sekolah_id  bigint not null,
    siswa_id    bigint not null,
    jenis       varchar(20) not null,
    menu_id     bigint,
    kategori_id bigint,
    nominal     bigint,
    alasan      varchar(500),
    aktif       boolean not null default true,
    diubah_oleh bigint,
    waktu       timestamptz not null default now(),
    created_at  timestamptz not null default now(),
    constraint ck_pembatasan_jenis check (jenis in ('BLOKIR_SISWA','BLOKIR_ITEM','LIMIT_HARIAN')),
    constraint ck_pembatasan_target check (not (menu_id is not null and kategori_id is not null)),
    constraint ck_pembatasan_nominal check (jenis <> 'LIMIT_HARIAN' or nominal is not null),
    constraint fk_pembatasan_siswa   foreign key (sekolah_id, siswa_id)
        references siswa (sekolah_id, id) on delete cascade,
    constraint fk_pembatasan_menu    foreign key (menu_id) references menu (id),
    constraint fk_pembatasan_kategori foreign key (kategori_id) references kategori_menu (id),
    constraint fk_pembatasan_sekolah foreign key (sekolah_id) references sekolah (id)
);

comment on table pembatasan is
    'Satu tabel untuk semua pembatasan siswa: blokir siswa, blokir menu/kategori, dan limit belanja harian.';

create unique index uq_pembatasan_subjek_jenis
    on pembatasan (sekolah_id, siswa_id, jenis, coalesce(menu_id, 0), coalesce(kategori_id, 0));

insert into pembatasan (sekolah_id, siswa_id, jenis, alasan, aktif, diubah_oleh, waktu)
select b.sekolah_id, b.subjek_id, 'BLOKIR_SISWA', b.alasan, b.diblokir, b.diubah_oleh, b.diubah_pada
from blokir_kartu b where b.subjek_tipe = 'SISWA';

insert into pembatasan (sekolah_id, siswa_id, jenis, menu_id, kategori_id, aktif, diubah_oleh, waktu)
select b.sekolah_id, b.subjek_id, 'BLOKIR_ITEM', b.menu_id, b.kategori_id, b.diblokir, b.diubah_oleh, b.diubah_pada
from blokir_item b where b.subjek_tipe = 'SISWA';

insert into pembatasan (sekolah_id, siswa_id, jenis, nominal, aktif, diubah_oleh, waktu)
select l.sekolah_id, l.subjek_id, 'LIMIT_HARIAN', l.nominal, true, l.diubah_oleh, l.diubah_pada
from limit_harian l where l.subjek_tipe = 'SISWA';

drop table blokir_kartu;
drop table blokir_item;
drop table limit_harian;

