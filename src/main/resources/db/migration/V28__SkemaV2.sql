-- Yang berubah:
--   1. tabel induk `sekolah` (semua sekolah_id sekarang ber-FK)
--   2. 12 tabel diganti nama (dev_pengguna -> pengguna, saldo_cache ->
--      saldo, saldo_ledger -> mutasi_saldo, dst)
--   3. dev_siswa_rfid dipecah jadi `siswa` + `kartu`
--   4. tabel baru `orang_tua` (satu siswa boleh punya >1 wali)
--   5. subjek_tipe/subjek_id (polimorfik: SISWA | KARTU_TAMU) -> siswa_id
--   6. blokir_kartu + blokir_item + limit_harian -> satu tabel `pembatasan`
--   7. kebijakan_kantin digabung ke pengaturan_kantin
--   8. kartu_tamu & webhook_event dihapus (tamu cukup bayar tunai)
--   9. kolom baru: transaksi.metode_bayar, sesi_kasir.uang_fisik/selisih/
--      catatan, setoran.status
