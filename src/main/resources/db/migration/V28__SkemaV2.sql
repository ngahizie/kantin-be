-- ---------------------------------------------------------------------
-- 1. Tabel induk sekolah
-- ---------------------------------------------------------------------
create table sekolah (
    id          bigint primary key,
    nama        varchar(150) not null,
    npsn        varchar(20),
    alamat      varchar(255),
    aktif       boolean not null default true,
    created_at  timestamptz not null default now()
);

-- isi dari sekolah_id yang sudah dipakai data lama
insert into sekolah (id, nama)
select distinct s.sekolah_id, 'Sekolah ' || s.sekolah_id
from (
    select sekolah_id from dev_pengguna
    union select sekolah_id from sekolah_kantin_config
    union select sekolah_id from titik_kasir
    union select sekolah_id from dev_siswa_rfid
    union select sekolah_id from menu
) s
where s.sekolah_id is not null;

comment on table sekolah is 'Induk semua data kantin. Satu baris = satu sekolah.';

