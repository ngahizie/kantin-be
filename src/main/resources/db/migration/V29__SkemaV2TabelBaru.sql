-- ---------------------------------------------------------------------
-- 1. SEKOLAH (tenant)
-- ---------------------------------------------------------------------
create table sekolah (
  id          bigint primary key,
  nama        varchar(120) not null,
  npsn        varchar(20) unique,
  alamat      varchar(255),
  aktif       boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. PENGGUNA (akun yang login)
-- ---------------------------------------------------------------------
create table pengguna (
  id             bigint generated by default as identity primary key,
  sekolah_id     bigint not null references sekolah(id) on delete cascade,
  nama           varchar(120) not null,
  username       varchar(60)  not null,
  peran          varchar(20)  not null
                 check (peran in ('KEPSEK','TATA_USAHA','PENGELOLA','PETUGAS','BENDAHARA','ADMIN_SEKOLAH')),
  password_hash  varchar(100) not null,
  aktif          boolean not null default true,
  dibuat_at      timestamptz not null default now(),
  constraint pengguna_username_unik unique (sekolah_id, username)
);

-- ---------------------------------------------------------------------
-- 3. SISWA
-- ---------------------------------------------------------------------
create table siswa (
  id          bigint primary key,
  sekolah_id  bigint not null references sekolah(id) on delete cascade,
  nis         varchar(20),
  nisn        varchar(20),
  nama        varchar(120) not null,
  kelas       varchar(20),
  foto_url    varchar(255),
  aktif       boolean not null default true,
  dibuat_at   timestamptz not null default now(),
  constraint siswa_nis_unik unique (sekolah_id, nis),
  -- dipakai FK gabungan supaya anak tabel tidak bisa menunjuk siswa sekolah lain
  constraint siswa_id_sekolah_unik unique (id, sekolah_id)
);

-- ---------------------------------------------------------------------
-- 4. ORANG TUA / WALI  (1 siswa boleh > 1 wali)
-- ---------------------------------------------------------------------
create table orang_tua (
  id             bigint generated by default as identity primary key,
  sekolah_id     bigint not null,
  siswa_id       bigint not null,
  nama           varchar(120) not null,
  telepon        varchar(20),
  hubungan       varchar(10) not null check (hubungan in ('AYAH','IBU','WALI')),
  punya_aplikasi boolean not null default false,
  aktif          boolean not null default true,
  constraint orang_tua_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id) on delete cascade,
  constraint orang_tua_unik unique (siswa_id, nama)
);

-- ---------------------------------------------------------------------
-- 5. KARTU (RFID)
-- ---------------------------------------------------------------------
create table kartu (
  uid          varchar(32) primary key,
  sekolah_id   bigint not null,
  siswa_id     bigint not null,
  nomor_kartu  varchar(40),
  aktif        boolean not null default true,
  dibuat_at    timestamptz not null default now(),
  constraint kartu_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id) on delete cascade,
  constraint kartu_nomor_unik unique (sekolah_id, nomor_kartu)
);
-- satu siswa hanya boleh punya 1 kartu aktif
create unique index kartu_satu_aktif_per_siswa on kartu (siswa_id) where aktif;

-- ---------------------------------------------------------------------
-- 6. KATEGORI MENU
-- ---------------------------------------------------------------------
create table kategori_menu (
  id          bigint generated by default as identity primary key,
  sekolah_id  bigint not null references sekolah(id) on delete cascade,
  nama        varchar(60) not null,
  urutan      int not null default 0,
  aktif       boolean not null default true,
  constraint kategori_menu_unik unique (sekolah_id, nama),
  constraint kategori_menu_id_sekolah_unik unique (id, sekolah_id)
);

-- ---------------------------------------------------------------------
-- 7. MENU
-- ---------------------------------------------------------------------
create table menu (
  id            bigint generated by default as identity primary key,
  sekolah_id    bigint not null,
  kategori_id   bigint not null,
  nama          varchar(120) not null,
  kode_barcode  varchar(60),
  satuan        varchar(20) not null default 'PORSI',
  foto_url      varchar(255),
  harga_jual    bigint not null check (harga_jual >= 0),
  hpp           bigint not null default 0 check (hpp >= 0),
  stok_minimum  int not null default 0,
  aktif         boolean not null default true,
  dibuat_at     timestamptz not null default now(),
  constraint menu_kategori_fk foreign key (kategori_id, sekolah_id)
    references kategori_menu (id, sekolah_id),
  constraint menu_unik unique (sekolah_id, nama),
  constraint menu_id_sekolah_unik unique (id, sekolah_id)
);

-- ---------------------------------------------------------------------
-- 8. STOK (1 baris per menu)
-- ---------------------------------------------------------------------
create table stok (
  menu_id       bigint primary key,
  sekolah_id    bigint not null,
  jumlah        int not null default 0,
  hpp           bigint not null default 0,
  stok_minimum  int not null default 0,
  diperbarui_at timestamptz not null default now(),
  constraint stok_menu_fk foreign key (menu_id, sekolah_id)
    references menu (id, sekolah_id) on delete cascade
);

-- ---------------------------------------------------------------------
-- 9. RIWAYAT STOK (kartu stok / ledger)
-- ---------------------------------------------------------------------
create table riwayat_stok (
  id                bigint generated by default as identity primary key,
  sekolah_id        bigint not null references sekolah(id) on delete cascade,
  menu_id           bigint not null references menu(id) on delete cascade,
  arah              varchar(6)  not null check (arah in ('MASUK','KELUAR')),
  jenis             varchar(20) not null
                    check (jenis in ('PEMBELIAN','PENJUALAN','PENYESUAIAN','RETUR','PEMBATALAN')),
  qty               int not null,
  stok_setelah      int not null,
  harga_beli_satuan bigint,
  hpp_snapshot      bigint not null default 0,
  transaksi_id      bigint,   -- FK ditambahkan di akhir file (tabel transaksi dibuat setelah ini)
  mutasi_asal_id    bigint references riwayat_stok(id),
  referensi_tipe    varchar(30),
  referensi_id      bigint,
  alasan            varchar(255),
  aktor_id          bigint references pengguna(id),
  aktor_nama        varchar(120),
  waktu             timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 10. TITIK KASIR
-- ---------------------------------------------------------------------
create table titik_kasir (
  id          bigint generated by default as identity primary key,
  sekolah_id  bigint not null references sekolah(id) on delete cascade,
  kode        varchar(30) not null,
  nama        varchar(80) not null,
  aktif       boolean not null default true,
  dibuat_at   timestamptz not null default now(),
  constraint titik_kasir_unik unique (sekolah_id, kode)
);

-- ---------------------------------------------------------------------
-- 11. SESI KASIR
-- ---------------------------------------------------------------------
create table sesi_kasir (
  id             bigint generated by default as identity primary key,
  sekolah_id     bigint not null references sekolah(id) on delete cascade,
  titik_kasir_id bigint not null references titik_kasir(id),
  tanggal        date not null default current_date,
  status         varchar(10) not null default 'TERBUKA'
                 check (status in ('TERBUKA','DITUTUP')),
  total_bruto    bigint not null default 0,
  total_void     bigint not null default 0,
  total_bersih   bigint not null default 0,
  uang_fisik     bigint,
  selisih        bigint,
  catatan        varchar(255),
  dibuka_at      timestamptz not null default now(),
  ditutup_at     timestamptz,
  ditutup_oleh   bigint references pengguna(id),
  auto_tutup     boolean not null default false
);
-- satu titik kasir hanya boleh punya 1 sesi terbuka
create unique index sesi_satu_terbuka_per_titik on sesi_kasir (titik_kasir_id) where status = 'TERBUKA';

-- ---------------------------------------------------------------------
-- 12. TRANSAKSI
-- ---------------------------------------------------------------------
create table transaksi (
  id              bigint generated by default as identity primary key,
  sekolah_id      bigint not null references sekolah(id) on delete cascade,
  sesi_kasir_id   bigint references sesi_kasir(id),
  titik_kasir_id  bigint references titik_kasir(id),
  siswa_id        bigint,
  metode_bayar    varchar(10) not null default 'SALDO'
                  check (metode_bayar in ('SALDO','TUNAI')),
  kartu_uid       varchar(32) references kartu(uid),
  petugas_id      bigint references pengguna(id),
  total           bigint not null check (total >= 0),
  total_hpp       bigint not null default 0,
  status          varchar(10) not null default 'BELANJA'
                  check (status in ('BELANJA','VOID')),
  alasan_void     varchar(40),
  void_at         timestamptz,
  void_oleh       bigint references pengguna(id),
  idempotency_key varchar(80) unique,
  waktu           timestamptz not null default now(),
  constraint transaksi_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id),
  -- bayar pakai saldo wajib ada siswanya; tunai boleh tanpa siswa
  constraint transaksi_saldo_wajib_siswa check (metode_bayar <> 'SALDO' or siswa_id is not null)
);

-- ---------------------------------------------------------------------
-- 13. TRANSAKSI ITEM
-- ---------------------------------------------------------------------
create table transaksi_item (
  id           bigint generated by default as identity primary key,
  transaksi_id bigint not null references transaksi(id) on delete cascade,
  menu_id      bigint not null references menu(id),
  nama_menu    varchar(120) not null,
  qty          int not null check (qty > 0),
  harga_satuan bigint not null,
  hpp_satuan   bigint not null default 0,
  subtotal     bigint not null
);

-- ---------------------------------------------------------------------
-- 14. SALDO (1 baris per siswa per sekolah)
-- ---------------------------------------------------------------------
create table saldo (
  sekolah_id    bigint not null references sekolah(id) on delete cascade,
  siswa_id      bigint not null,
  saldo         bigint not null default 0 check (saldo >= 0),
  diperbarui_at timestamptz not null default now(),
  primary key (sekolah_id, siswa_id),
  constraint saldo_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id) on delete cascade
);

-- ---------------------------------------------------------------------
-- 15. MUTASI SALDO (ledger)
-- ---------------------------------------------------------------------
create table mutasi_saldo (
  id              bigint generated by default as identity primary key,
  sekolah_id      bigint not null,
  siswa_id        bigint not null,
  arah            varchar(6) not null check (arah in ('KREDIT','DEBIT')),
  jenis           varchar(20) not null
                  check (jenis in ('TOPUP_TUNAI','TOPUP_ONLINE','PEMBELIAN','REFUND','PENYESUAIAN')),
  nominal         bigint not null check (nominal > 0),
  saldo_setelah   bigint not null,
  transaksi_id    bigint references transaksi(id),
  referensi_tipe  varchar(30),
  referensi_id    bigint,
  idempotency_key varchar(80) unique,
  keterangan      varchar(255),
  aktor_id        bigint references pengguna(id),
  waktu           timestamptz not null default now(),
  constraint mutasi_saldo_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id) on delete cascade
);

-- ---------------------------------------------------------------------
-- 16. SETORAN (setoran kasir ke TU)
-- ---------------------------------------------------------------------
create table setoran (
  id               bigint generated by default as identity primary key,
  sekolah_id       bigint not null references sekolah(id) on delete cascade,
  tanggal          date not null,
  petugas_id       bigint references pengguna(id),
  total_transaksi  bigint not null default 0,
  total_topup      bigint not null default 0,
  total_sistem     bigint not null default 0,
  uang_fisik       bigint,
  selisih          bigint,
  status           varchar(24) not null default 'MENUNGGU_KONFIRMASI'
                   check (status in ('MENUNGGU_KONFIRMASI','DIKONFIRMASI')),
  catatan          varchar(255),
  dikonfirmasi_oleh bigint references pengguna(id),
  konfirmasi_pada  timestamptz,
  dibuat_at        timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 17. PENGATURAN KANTIN (1 baris per sekolah)
-- ---------------------------------------------------------------------
create table pengaturan_kantin (
  sekolah_id               bigint primary key references sekolah(id) on delete cascade,
  nama_kantin              varchar(80) not null default 'Kantin Sekolah',
  jam_tutup_otomatis       time not null default '15:00',
  konfirmasi_manual        boolean not null default false,
  durasi_foto_detik        int not null default 3,
  min_topup                bigint not null default 5000,
  maks_topup               bigint not null default 500000,
  batas_saldo_siswa        bigint not null default 1000000,
  kebijakan_saldo_mengendap varchar(20) not null default 'REFUND'
                           check (kebijakan_saldo_mengendap in ('REFUND','PERINGATAN','ABAIKAN')),
  ambang_hari              int not null default 30,
  diperbarui_oleh          bigint references pengguna(id),
  updated_at               timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 18. PEMBATASAN (gabungan blokir kartu + blokir menu + limit harian)
-- ---------------------------------------------------------------------
create table pembatasan (
  id          bigint generated by default as identity primary key,
  sekolah_id  bigint not null,
  siswa_id    bigint,
  jenis       varchar(20) not null
              check (jenis in ('BLOKIR_KARTU','BLOKIR_MENU','BLOKIR_KATEGORI','LIMIT_HARIAN')),
  menu_id     bigint references menu(id) on delete cascade,
  kategori_id bigint references kategori_menu(id) on delete cascade,
  nominal     bigint,
  alasan      varchar(255),
  aktif       boolean not null default true,
  diubah_oleh bigint references pengguna(id),
  waktu       timestamptz not null default now(),
  constraint pembatasan_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id) on delete cascade,
  -- bentuk tiap jenis harus jelas
  constraint pembatasan_bentuk check (
    (jenis = 'BLOKIR_KARTU'    and siswa_id is not null and menu_id is null     and kategori_id is null) or
    (jenis = 'BLOKIR_MENU'     and siswa_id is not null and menu_id is not null and kategori_id is null) or
    (jenis = 'BLOKIR_KATEGORI' and siswa_id is not null and menu_id is null     and kategori_id is not null) or
    (jenis = 'LIMIT_HARIAN'    and siswa_id is not null and menu_id is null     and kategori_id is null and nominal is not null)
  )
);

-- ---------------------------------------------------------------------
-- 19. TRANSAKSI TERTUNDA (tunai yang butuh konfirmasi)
-- ---------------------------------------------------------------------
create table transaksi_tertunda (
  id              bigint generated by default as identity primary key,
  sekolah_id      bigint not null references sekolah(id) on delete cascade,
  titik_kasir_id  bigint references titik_kasir(id),
  siswa_id        bigint,
  petugas_id      bigint references pengguna(id),
  total           bigint not null,
  status          varchar(20) not null default 'MENUNGGU_KONFIRMASI'
                  check (status in ('MENUNGGU_KONFIRMASI','DIKONFIRMASI','DITOLAK','KEDALUWARSA')),
  idempotency_key varchar(80) unique,
  items_json      text not null,
  kedaluwarsa_at  timestamptz,
  dibuat_at       timestamptz not null default now(),
  constraint transaksi_tertunda_siswa_fk foreign key (siswa_id, sekolah_id)
    references siswa (id, sekolah_id)
);

-- ---------------------------------------------------------------------
-- 20. AKUN BUKU KAS
-- ---------------------------------------------------------------------
create table akun_buku_kas (
  id          bigint generated by default as identity primary key,
  sekolah_id  bigint not null references sekolah(id) on delete cascade,
  nama        varchar(80) not null,
  tipe        varchar(10) not null check (tipe in ('MASUK','KELUAR')),
  aktif       boolean not null default true,
  constraint akun_buku_kas_unik unique (sekolah_id, nama)
);

-- ---------------------------------------------------------------------
-- 21. JURNAL BUKU KAS
-- ---------------------------------------------------------------------
create table jurnal_buku_kas (
  id           bigint generated by default as identity primary key,
  sekolah_id   bigint not null references sekolah(id) on delete cascade,
  akun_id      bigint not null references akun_buku_kas(id),
  referensi_id bigint references transaksi(id),
  jumlah       bigint not null,
  status       varchar(20) not null default 'TERCATAT'
               check (status in ('TERCATAT','DIBATALKAN')),
  waktu        timestamptz not null default now(),
  constraint jurnal_unik unique (akun_id, referensi_id)
);

-- ---------------------------------------------------------------------
-- 22. CATATAN AUDIT
-- ---------------------------------------------------------------------
create table catatan_audit (
  id          bigint generated by default as identity primary key,
  sekolah_id  bigint not null references sekolah(id) on delete cascade,
  aktor_id    bigint references pengguna(id),
  aksi        varchar(40) not null,
  entitas     varchar(40),
  entitas_id  bigint,
  nilai_lama  text,
  nilai_baru  text,
  alasan      varchar(255),
  waktu       timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 23. KEJADIAN OFFLINE
-- ---------------------------------------------------------------------
create table kejadian_offline (
  id              bigint generated by default as identity primary key,
  sekolah_id      bigint not null references sekolah(id) on delete cascade,
  titik_kasir_id  bigint references titik_kasir(id),
  mulai           timestamptz not null,
  selesai         timestamptz,
  durasi_menit    int,
  keterangan      text,
  dilaporkan_oleh bigint references pengguna(id)
);

-- FK riwayat_stok -> transaksi (dipisah karena urutan pembuatan tabel)
alter table riwayat_stok
  add constraint riwayat_stok_transaksi_fk
  foreign key (transaksi_id) references transaksi(id) on delete set null;

-- =====================================================================
-- INDEX bantu laporan (kolom yang sering difilter/diurutkan)
-- =====================================================================
create index idx_siswa_sekolah      on siswa (sekolah_id);
create index idx_orang_tua_siswa    on orang_tua (siswa_id);
create index idx_kartu_sekolah      on kartu (sekolah_id);
create index idx_menu_sekolah       on menu (sekolah_id);
create index idx_riwayat_stok_menu  on riwayat_stok (menu_id, waktu desc);
create index idx_riwayat_stok_trx   on riwayat_stok (transaksi_id);
create index idx_transaksi_sekolah  on transaksi (sekolah_id, waktu desc);
create index idx_transaksi_siswa    on transaksi (siswa_id, waktu desc);
create index idx_transaksi_sesi     on transaksi (sesi_kasir_id);
create index idx_transaksi_item_trx on transaksi_item (transaksi_id);
create index idx_mutasi_siswa       on mutasi_saldo (siswa_id, waktu desc);
create index idx_mutasi_trx         on mutasi_saldo (transaksi_id);
create index idx_setoran_sekolah    on setoran (sekolah_id, tanggal desc);
create index idx_pembatasan_siswa   on pembatasan (sekolah_id, siswa_id) where aktif;
create index idx_audit_sekolah      on catatan_audit (sekolah_id, waktu desc);
create index idx_jurnal_sekolah     on jurnal_buku_kas (sekolah_id, waktu desc);
create index idx_offline_sekolah    on kejadian_offline (sekolah_id, mulai desc);
create index idx_sesi_sekolah       on sesi_kasir (sekolah_id, tanggal desc);
